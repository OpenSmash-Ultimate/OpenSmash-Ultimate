#!/usr/bin/env python3
"""The debug overlay's glyph atlas for a Linux build made on Linux: what make_overlay_font.c draws
with GDI on Windows (Consolas, bold, 40 pixels, white on black), drawn here with Pillow from the
system's bold monospace font, into the same C header (overlay_font.h, a build product).

Usage: make_overlay_font.py <output header> [font file]

Without a font file: fontconfig's "monospace:bold" (DejaVu Sans Mono Bold on most systems), else
one of the usual monospace fonts, else Pillow's own font."""
from pathlib import Path
import os
import shutil
import subprocess
import sys
import unicodedata

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from localization import font_layout
CELL_W, CELL_H, COLS, ROWS, GLYPHS = font_layout()
ATLAS_W, ATLAS_H = CELL_W * COLS, CELL_H * ROWS
SIZE = 40   # (CreateFontW(-40): a 40-pixel em)
KNOWN = ["/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf",        # Debian, Ubuntu
         "/usr/share/fonts/dejavu-sans-mono-fonts/DejaVuSansMono-Bold.ttf",  # Fedora
         "/usr/share/fonts/TTF/DejaVuSansMono-Bold.ttf",                     # Arch
         "/usr/share/fonts/truetype/DejaVuSansMono-Bold.ttf",                # openSUSE
         "/usr/share/fonts/truetype/liberation/LiberationMono-Bold.ttf",
         "/usr/share/fonts/liberation-mono/LiberationMono-Bold.ttf"]


def find_font():
    if shutil.which("fc-match"):
        r = subprocess.run(["fc-match", "-f", "%{file}", "monospace:bold"], capture_output=True, text=True)
        if r.returncode == 0 and os.path.isfile(r.stdout.strip()):
            return r.stdout.strip()
    return next((p for p in KNOWN if os.path.isfile(p)), None)


def atlas(font):
    """The atlas's coverage, one byte per pixel, rows top to bottom."""
    from PIL import Image, ImageDraw
    img = Image.new("L", (ATLAS_W, ATLAS_H), 0)
    draw = ImageDraw.Draw(img)
    for c in range(32, 127):
        x, y = (c - 32) % COLS * CELL_W, (c - 32) // COLS * CELL_H + 2
        draw.text((x, y), chr(c), fill=255, font=font, anchor="la")   # (the top of the line, as GDI's TextOut)
    from PIL import ImageFont
    fallbacks = {}
    def glyph_font(cp):
        if unicodedata.east_asian_width(chr(cp)) not in ("W", "F"):
            return font
        language = "ko" if 0xac00 <= cp <= 0xd7af else "ja" if 0x3040 <= cp <= 0x30ff else "zh-cn"
        if language not in fallbacks:
            fallback = font
            if shutil.which("fc-match"):
                result = subprocess.run(["fc-match", "-f", "%{file}", "sans-serif:lang=" + language], capture_output=True, text=True)
                if result.returncode == 0 and os.path.isfile(result.stdout.strip()):
                    fallback = ImageFont.truetype(result.stdout.strip(), 38)
            fallbacks[language] = fallback
        return fallbacks[language]
    for i, cp in enumerate(GLYPHS):
        cell = 96 + i * 2
        draw.text((cell % COLS * CELL_W, cell // COLS * CELL_H + 2), chr(cp), fill=255, font=glyph_font(cp), anchor="la")
    return img.tobytes()


def header(coverage):
    out = [f"/* Generated by tools/linux/make_overlay_font.py: {ATLAS_W}x{ATLAS_H} coverage, printable ASCII in "
           f"{CELL_W}x{CELL_H} cells. */\n", f"static const unsigned char overlay_font[{ATLAS_W * ATLAS_H}] = {{\n"]
    for i in range(0, len(coverage), 32):
        out.append("".join(f"{v}," for v in coverage[i:i + 32]) + "\n")
    out.append("};\n")
    return "".join(out)


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    from PIL import ImageFont
    path = sys.argv[2] if len(sys.argv) > 2 else find_font()
    if path:
        font = ImageFont.truetype(path, SIZE)
    else:
        print("no monospace font found: the overlay uses Pillow's own font")
        font = ImageFont.load_default(SIZE)
    with open(sys.argv[1], "w", newline="\n") as f:
        f.write(header(atlas(font)))
    print(f"wrote {sys.argv[1]} ({path or 'Pillow font'})")


if __name__ == "__main__":
    main()
