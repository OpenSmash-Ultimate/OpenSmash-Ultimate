"""Compile shared UI catalogs. Run after editing locales/*.json; --check is CI-safe.

English source text is the message ID (gettext style). Untranslated/changed text falls
back to the source. Catalogs never contain setting keys, paths or network values.
Only the Python standard library is needed; the generated C table is committed.
"""
import argparse
import json
from pathlib import Path
import re
import string

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / 'runtime/ui_catalog.generated.h'
PRINTF = re.compile(r'%(?:[-+ #0]*)(?:\d+|\*)?(?:\.(?:\d+|\*))?(?:hh|ll|[hljztL])?[diuoxXfFeEgGaAcspn%]')


def placeholders(text):
    c = []
    for match in PRINTF.finditer(text):
        if match[0] == '%%':
            continue
        # A prose percentage such as "80% strength" is not a printf conversion.
        # Keep real conversions adjacent to digits, such as "2%s", visible to validation.
        if match.start() and text[match.start() - 1].isdigit() and re.match(r'% +[A-Za-z]{2,}', text[match.start():]):
            continue
        c.append(match[0])
    try:
        net = sorted((name, spec, conv) for _, name, spec, conv in string.Formatter().parse(text) if name is not None)
    except ValueError as e:
        raise ValueError(f'invalid braces: {text!r}') from e
    return c, net


def load_catalogs(folder=None):
    catalogs = []
    for path in sorted((folder or ROOT / 'locales').glob('*.json')):
        def unique(pairs):
            out = {}
            for key, value in pairs:
                if key in out:
                    raise ValueError(f'{path.name}: duplicate key {key!r}')
                out[key] = value
            return out
        data = json.loads(path.read_text(encoding='utf-8'), object_pairs_hook=unique)
        if not re.fullmatch(r'[a-z]{2,3}(?:-[A-Za-z0-9]+)*', path.stem):
            raise ValueError(f'invalid locale: {path.stem}')
        if not isinstance(data.get('name'), str) or not isinstance(data.get('messages'), dict):
            raise ValueError(f'{path.name}: expected name and messages')
        for source, target in data['messages'].items():
            if not source or not isinstance(target, str) or not target or '\0' in source + target:
                raise ValueError(f'{path.name}: invalid message {source!r}')
            if placeholders(source) != placeholders(target):
                raise ValueError(f'{path.name}: changed placeholders in {source!r}')
        catalogs.append((path.stem, data))
    if not any(code == 'en' for code, _ in catalogs):
        raise ValueError('English fallback (en.json) is required')
    return sorted(catalogs, key=lambda item: (item[0] != 'en', item[0]))


def c_string(text):
    # UTF-8 bytes as octal: independent of the C compiler's source/execution code page.
    return '"' + ''.join(chr(b) if 32 <= b < 127 and b not in (34, 92) else f'\\{b:03o}' for b in text.encode()) + '"'


def expanded_messages(messages):
    result = dict(messages)
    for source, text in messages.items():
        if '%' not in source and '{' not in source:
            result.setdefault(source.upper(), text)
    return result


def catalog_glyphs(catalogs):
    return sorted({ord(c) for _, data in catalogs for text in [data['name'], *data['messages'], *data['messages'].values()] for c in text if ord(c) >= 128})


def font_layout(catalogs=None):
    glyphs = catalog_glyphs(catalogs if catalogs is not None else load_catalogs())
    cell_w, cell_h, columns = 24, 48, 64
    rows = (96 + len(glyphs) * 2 + columns - 1) // columns
    return cell_w, cell_h, columns, rows, glyphs


def generate(catalogs):
    lines = ['/* Generated by tools/localization.py; edit locales/*.json, not this file. */', '#pragma once',
             'typedef struct { const char *source, *text; } UiMessage;',
             'typedef struct { const char *code, *name; const UiMessage *messages; unsigned count; } UiCatalog;']
    for i, (_, data) in enumerate(catalogs):
        messages = sorted(expanded_messages(data['messages']).items())
        if messages:
            lines.append(f'static const UiMessage ui_messages_{i}[] = {{')
            lines.extend('    {' + c_string(k) + ', ' + c_string(v) + '},' for k, v in messages)
            lines.append('};')
    lines.append('static const UiCatalog ui_catalogs[] = {')
    for i, (code, data) in enumerate(catalogs):
        table = f'ui_messages_{i}' if data['messages'] else 'NULL'
        lines.append(f'    {{{c_string(code)}, {c_string(data["name"])}, {table}, {len(expanded_messages(data["messages"]))}}},')
    lines.extend(['};', '#define UI_CATALOG_COUNT (sizeof ui_catalogs / sizeof *ui_catalogs)'])
    glyphs = catalog_glyphs(catalogs)
    lines.append('static const unsigned ui_glyphs[] = {' + ','.join(map(str, glyphs)) + '};')
    lines.extend([f'#define UI_GLYPH_COUNT {len(glyphs)}', '#define UI_FONT_COLS 64',
                  '#define UI_FONT_ROWS ((96 + UI_GLYPH_COUNT * 2 + UI_FONT_COLS - 1) / UI_FONT_COLS)'])
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='validate catalogs and reject stale generated output')
    args = parser.parse_args()
    try:
        catalogs = load_catalogs()
        result = generate(catalogs)
        if args.check:
            if not OUTPUT.exists() or OUTPUT.read_text(encoding='utf-8') != result:
                parser.exit(1, 'UI catalogs are stale; run python tools/localization.py\n')
        else:
            OUTPUT.write_text(result, encoding='utf-8', newline='\n')
        print(f'UI catalogs valid: {len(catalogs)} languages, {sum(len(d["messages"]) for _, d in catalogs)} translations')
    except (ValueError, OSError) as e:
        parser.exit(1, f'{e}\n')


if __name__ == '__main__':
    main()
